;******************************************************************************
; @file             ExitProcess.asm
;******************************************************************************
%ifndef     HEX
% define        HEX(y)                  0x##y
%endif

;******************************************************************************
; @function        ExitProcess
;******************************************************************************
global      ExitProcess
ExitProcess:

    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    ;; Reserve Microsoft x64 shadow space and align the stack.
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    sub     rsp,    40

    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    ;; Terminate the current process.
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    mov     edx,    ecx
    mov     rcx,    -1
    call    NtTerminateProcess

.wait:

    jmp     .wait
