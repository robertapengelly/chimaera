;******************************************************************************
; @file             ExitProcess.asm
;******************************************************************************
.option     segment:use32
.386

%ifndef     HEX
% define        HEX(y)                  0x##y
%endif

;******************************************************************************
; @function        _ExitProcess
;******************************************************************************
global      _ExitProcess
_ExitProcess:

    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    ;; Terminate the current process.
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    push    dword ptr [esp + 4]
    push    -1
    call    _NtTerminateProcess@8

.wait:

    jmp     .wait
