%ifndef     HEX
% define        HEX(y)                  0x##y
%endif

;******************************************************************************
; @function         mainCRTStartup
;******************************************************************************
global      mainCRTStartup
mainCRTStartup:

    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    ;; Zero out rbp.
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    xor     rbp,    rbp
    
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    ;; Align the stack and reserve Microsoft x64 shadow space and locals.
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    and     rsp,    -16
    sub     rsp,    80
    
    mov     dword ptr [rsp + 64],    0
    
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    ;; Retrieve the command-line arguments and environment.
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    lea     rcx,    [rsp + 40]
    lea     rdx,    [rsp + 48]
    lea     r8,     [rsp + 56]
    
    xor     r9d,    r9d
    lea     rax,    [rsp + 64]
    
    mov     qword ptr [rsp + 32],    rax
    call    __getmainargs
    
    test    eax,    eax
    jnz     .failed
    
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    ;; Call the application's main function.
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    mov     ecx,    dword ptr [rsp + 40]
    mov     rdx,    qword ptr [rsp + 48]
    mov     r8,     qword ptr [rsp + 56]
    call    main
    
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    ;; Terminate the process with main's return value.
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    mov     ecx,    eax
    call    exit
    
    jmp     wait

.failed:

    mov     ecx,    1
    call    exit

;******************************************************************************
; @function         wait
;******************************************************************************
wait:

    jmp     wait
