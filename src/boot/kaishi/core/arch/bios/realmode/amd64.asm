    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    ;; NULL Descriptor.
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    dw      HEX (0000)
    dw      HEX (0000)
    dw      HEX (0000)
    dw      HEX (0000)
    
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    ;; ...
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    dw      HEX (0000)
    dw      HEX (0000)
    dw      HEX (0000)
    dw      HEX (0000)
    
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    ;; Long Mode Code Descriptor.
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    dw      HEX (0000)
    dw      HEX (0000)
    dw      HEX (9A00)
    dw      HEX (0020)
    
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    ;; Long Mode Data Descriptor.
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    dw      HEX (0000)
    dw      HEX (0000)
    dw      HEX (9200)
    dw      HEX (0000)
    
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    ;; 16-bit Realmode Code Descriptor.
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    dw      HEX (FFFF)
    dw      HEX (0000)
    dw      HEX (9A00)
    dw      HEX (008F)
    
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    ;; 16-bit Realmode Data Descriptor.
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    dw      HEX (FFFF)
    dw      HEX (0000)
    dw      HEX (9200)
    dw      HEX (0000)
    
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    ;; Compat Mode Code Descriptor.
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    dw      HEX (FFFF)
    dw      HEX (0000)
    dw      HEX (9A00)
    dw      HEX (00CF)
    
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    ;; 32-bit flat data descriptor
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    dw      HEX (FFFF)
    dw      HEX (0000)
    dw      HEX (9200)
    dw      HEX (00CF)

gdt_size:           equ     ($ - gdt_table) - 1

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;; FNID_* functions.
;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
callback_table:

    dw      0,  0
    dw      0,  0

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
; @function         build_page_tables
;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
build_page_tables:

    pushad
    push    es
    
    cld
    
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    ;; ES = flat/zero segment for physical writes.
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    xor     eax,    eax
    mov     es,     eax
    
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    ;; Clear PML4.
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    mov     ebx,    offset pml4_addr
    mov     edx,    ebx
    
    and     ebx,    HEX (0F)
    shr     edx,    4
    
    mov     es,     edx
    mov     eax,    dword ptr es:[ebx]
    
    shr     eax,    4
    mov     es,     ax
    
    xor     edi,    edi
    xor     eax,    eax
    mov     ecx,    1024
    rep     stosd
    
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    ;; Clear PDP.
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    mov     ebx,    offset pdp_addr
    mov     edx,    ebx
    
    and     ebx,    HEX (0F)
    shr     edx,    4
    
    mov     es,     edx
    mov     eax,    dword ptr es:[ebx]
    
    shr     eax,    4
    mov     es,     ax
    
    xor     edi,    edi
    xor     eax,    eax
    mov     ecx,    1024
    rep     stosd
    
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    ;; Clear PD.
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    mov     ebx,    offset pd_addr
    mov     edx,    ebx
    
    and     ebx,    HEX (0F)
    shr     edx,    4
    
    mov     es,     edx
    mov     eax,    dword ptr es:[ebx]
    
    shr     eax,    4
    mov     es,     ax
    
    xor     edi,    edi
    xor     eax,    eax
    mov     ecx,    1024
    rep     stosd
    
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    ;; PML4[0] = PDP | present | rw
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    mov     ebx,    offset pml4_addr
    mov     edx,    ebx
    
    and     ebx,    HEX (0F)
    shr     edx,    4
    
    mov     es,     edx
    mov     eax,    dword ptr es:[ebx]
    
    shr     eax,    4
    mov     es,     ax
    
    xor     edi,    edi
    
    mov     ebx,    offset pdp_addr
    mov     edx,    ebx
    
    and     ebx,    HEX (0F)
    shr     edx,    4
    
    mov     fs,     edx
    mov     eax,    dword ptr fs:[ebx]
    
    or      eax,    HEX (03)
    
    mov     dword ptr es:[edi + 0],     eax
    mov     dword ptr es:[edi + 4],     0
    
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    ;; PDP[0] = PD | present | rw
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    mov     ebx,    offset pdp_addr
    mov     edx,    ebx
    
    and     ebx,    HEX (0F)
    shr     edx,    4
    
    mov     es,     edx
    mov     eax,    dword ptr es:[ebx]
    
    shr     eax,    4
    mov     es,     ax
    
    xor     edi,    edi
    
    mov     ebx,    offset pd_addr
    mov     edx,    ebx
    
    and     ebx,    HEX (0F)
    shr     edx,    4
    
    mov     fs,     edx
    mov     eax,    dword ptr fs:[ebx]
    
    or      eax,    HEX (03)
    
    mov     dword ptr es:[edi + 0],     eax
    mov     dword ptr es:[edi + 4],     0
    
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    ;; PD[0..511] = 2 MiB identity pages.
    ;; Flags: present | rw | page-size = 0x83.
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    mov     ebx,    offset pd_addr
    mov     edx,    ebx
    
    and     ebx,    HEX (0F)
    shr     edx,    4
    
    mov     es,     edx
    mov     eax,    dword ptr es:[ebx]
    
    shr     eax,    4
    mov     es,     ax
    
    xor     edi,    edi
    mov     ecx,    512
    mov     eax,    HEX (83)

build_page_tables.bpt2:

    mov     dword ptr es:[edi + 0],     eax
    mov     dword ptr es:[edi + 4],     0
    
    add     eax,    512 * 4096
    add     edi,    8
    
    dec     ecx
    jnz     build_page_tables.bpt2
    
    pop     es
    popad
    ret

