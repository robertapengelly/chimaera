; @file             strlen.asm
;******************************************************************************
%ifndef     HEX
% define        HEX(y)                  0x##y
%endif

;******************************************************************************
; @function        strlen
;******************************************************************************
global      strlen
strlen:

    push    rsi
    push    r12

.L3:

    mov     rsi,    rcx
    xor     r12,    r12

.L2:

    lodsb
    
    and     al,     al
    jz      .L1
    
    inc     r12
    jmp     .L2

.L1:

    mov     rax,    r12
    
    pop     r12
    pop     rsi
    
    ret
