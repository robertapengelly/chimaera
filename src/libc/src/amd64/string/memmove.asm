;******************************************************************************
; @file             memmove.asm
;******************************************************************************
%ifndef     HEX
% define        HEX(y)                  0x##y
%endif

;******************************************************************************
; @function        memmove
;******************************************************************************
global      memmove
memmove:

    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    ;; Preserve registers.
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    push    rsi
    push    rdi
    
    mov     rax,    rcx
    mov     rdi,    rcx
    mov     rsi,    rdx
    mov     rcx,    r8
    
    cmp     rdi,    rsi
    jbe     .L2
    
    test    rcx,    rcx
    jz      .L1
    
    lea     rdi,    [rdi + rcx - 1]
    lea     rsi,    [rsi + rcx - 1]
    
    std
    rep     movsb
    
    cld
    jmp     .L1

.L2:

    cld
    rep     movsb

.L1:

    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    ;; Restore registers and return.
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    pop     rdi
    pop     rsi
    ret
