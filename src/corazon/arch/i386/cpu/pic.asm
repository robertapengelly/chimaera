;******************************************************************************
; @file             pic.asm
;******************************************************************************
.option     segment:use32
.386

%ifndef     HEX
% define        HEX(y)                  0x##y
%endif

%define     ICW1_ICW4                   HEX (01)
%define     ICW1_INIT                   HEX (10)

;******************************************************************************
; @function         _pic_wait
;******************************************************************************
_pic_wait:

    xor     al,     al
    out     HEX (80),   al
    ret

;******************************************************************************
; @function         _irq_remap
;******************************************************************************
_irq_remap:

    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    ;; Cascade initialization.
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    mov     al,     ICW1_INIT | ICW1_ICW4
    out     HEX (20),   al      ; PIC1_COMMAND
    
    call    _pic_wait
    
    mov     al,     ICW1_INIT | ICW1_ICW4
    out     HEX (A0),   al      ; PIC2_COMMAND
    
    call    _pic_wait
    
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    ;; Remap.
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    mov     al,     HEX (20)    ; PIC1_OFFSET
    out     HEX (21),   al      ; PIC1_DATA
    
    call    _pic_wait
    
    mov     al,     HEX (28)    ; PIC2_OFFSET
    out     HEX (A1),   al      ; PIC2_DATA
    
    call    _pic_wait
    
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    ;; Cascade identity with slave PIC at IRQ2
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    mov     al,     HEX (04)
    out     HEX (21),   al      ; PIC1_DATA
    
    call    _pic_wait
    
    mov     al,     HEX (02)
    out     HEX (A1),   al      ; PIC2_DATA
    
    call    _pic_wait
    
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    ;; Request 8086 mode on each PIC.
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    mov     al,     HEX (01)
    out     HEX (21),   al      ; PIC1_DATA
    
    call    _pic_wait
    
    mov     al,     HEX (01)
    out     HEX (A1),   al      ; PCI2_DATA
    
    call    _pic_wait
    ret


;******************************************************************************
; @function         _irq_ack
;******************************************************************************
global      _irq_ack
_irq_ack:

    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    ;; Select ISR on the master PIC.
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    mov     al,     HEX (0B)
    out     HEX (20),   al
    
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    ;; Select ISR on the slave PIC.
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    mov     al,     HEX (0B)
    out     HEX (A0),   al
    
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    ;; Read the master ISR.
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    in      al,     HEX (20)
    mov     dl,     al
    
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    ;; Read the slave ISR.
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    in      al,     HEX (A0)
    mov     dh,     al
    
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    ;; If the slave has anything in service, acknowledge the slave first,
    ;; then the master cascade.
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    test    dh,     dh
    jz      .master
    
    mov     al,     HEX (20)
    out     HEX (A0),   al
    out     HEX (20),   al
    
    ret

.master:

    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    ;; Otherwise acknowledge the master if it has anything in service.
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    test    dl,     dl
    jz      .done
    
    mov     al,     HEX (20)
    out     HEX (20),   al

.done:

    ret

;******************************************************************************
; @function         _pic_initialize
;******************************************************************************
global      _pic_initialize
_pic_initialize:

    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    ;; Remap.
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    call    _irq_remap
    
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    ;; Return to caller.
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    ret
