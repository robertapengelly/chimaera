/******************************************************************************
 * @file            main.c
 *****************************************************************************/
#include    <stdio.h>

/******************************************************************************
 * @function        main
 *****************************************************************************/
int main (int argc, char **argv) {

    int i;
    
    if (argc < 2) {
        return 0;
    }
    
    for (i = 1; i < argc; i++) {
    
        printf ("%s", argv[i]);
        
        if (i < argc - 1) {
            printf (" ");
        } else {
            printf ("\n");
        }
    
    }
    
    return 0;

}
