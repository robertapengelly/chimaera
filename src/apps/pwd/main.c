#include    <stdio.h>
#include    <unistd.h>

/******************************************************************************
 * @function        main
 *****************************************************************************/
int main (int argc, char **argv) {

    char path[4096];
    
    if (!getcwd (path, sizeof (path))) {
        return 1;
    }
    
    printf ("%.*s\n", sizeof (path), path);
    
    (void) argc;
    (void) argv;
    
    return 0;

}
